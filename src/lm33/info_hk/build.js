// builds info_hk.js from labelled.js (+ 'site:<key>' twins and site building labels), in the lm31 data contract
const fs=require('fs'),path=require('path');
const T=require(path.join(__dirname,'..','..','hk','targets.json'));
const lab0=require('./labelled.js'), v39=require('./labelled_v39.js'), subs=lab0.__subs;
// v39: the v38 landmarks (hkx_*) and the v39 harbour front (hkv_*) from labelled_v39.js; a key must not be in both files
for(const k in v39) if(!k.startsWith('__')&&lab0[k]) throw new Error('in both files '+k);
const lab=Object.assign({},lab0,v39), twins=[...lab0.__siteTwins,...(v39.__siteTwins||[])];
const order=[]; for(const g in T.groups) for(const t of T.groups[g]) order.push([g,t]);
let out=`/* City Brush v39 · landmark intro cards · Hong Kong (all ${order.length} targets of hk/targets.json, the v39 harbour-front keys, plus site entries)
   Data contract: SC/lm31/BRIEF.md. Labelled keys: k kind, y year, a architect, h height m, fl floors, d description, x extra facts.
   'site:<key>' copies exist for the targets that may be built as SITES (the site key = the target key), and a few
   'site:<key>:<OSM en name>' entries for site building labels. Secondary pieces (<key>_b …) need no entry: the card resolves
   them to their parent by key prefix. Original writing; fields left out where not certain. Generated by build.js. */
Object.assign(window.LM_INFO = window.LM_INFO || {}, {\n`;
let g0=null;
for(const [g,t] of order){ const e=lab[t.key]; if(!e) throw new Error('missing '+t.key);
  if(g!==g0){ out+=`\n  /* ${g} */\n`; g0=g; }
  out+=`  ${t.key}: ${JSON.stringify(e)},\n`; }
const v39extra=Object.keys(v39).filter(k=>!k.startsWith('__')&&!order.some(([g,t])=>t.key===k));
out+=`\n  /* v39 harbour front (hk/hkv_island, hk/hkv_kowloon; not in targets.json) */\n`;
for(const k of v39extra) out+=`  ${k}: ${JSON.stringify(lab[k])},\n`;
out+=`\n  /* sites (same text as the target; used if the target is built as a SITE) */\n`;
for(const k of twins){ if(!lab[k]) throw new Error('twin '+k); out+=`  ${JSON.stringify('site:'+k)}: ${JSON.stringify(lab[k])},\n`; }
out+=`\n  /* site building labels */\n`;
for(const k in subs) out+=`  ${JSON.stringify(k)}: ${JSON.stringify(subs[k])},\n`;
out+='});\n';
fs.writeFileSync(path.join(__dirname,'info_hk.js'),out);
const extra=Object.keys(lab).filter(k=>!k.startsWith('__')&&!order.some(([g,t])=>t.key===k)&&!v39extra.includes(k));
console.log('targets',order.length,'v39 extra',v39extra.length,'site twins',twins.length,'subs',Object.keys(subs).length,'extra',extra,'bytes',out.length);
