#!/bin/bash
# lm50: regenerate the node landmark harness R/lm50/kit_sg/lmbase.js from the built Singapore app (R/../site/app.js).
# (The lm16-lm40 SC/sgreal/kit/lmbase.js no longer exists; this slices the same helper block — LMCTX ... lmMerge — out of the
#  production app, so builds use exactly the app's helpers.)  usage: bash R/lm50/kit_sg/mklmbase.sh [app.js]
APP=${1:-/home/claude/earth_online/site/app.js}; K=$(dirname "$0")
a=$(grep -n '^let LMCTX = null;' "$APP" | head -1 | cut -d: -f1); b=$(grep -n '^const LANDMARKS = {' "$APP" | head -1 | cut -d: -f1)
{ echo "// GENERATED by lm50/sg/kit/mklmbase.sh from $APP lines $a..$((b-1)) — do not edit"
  echo "var HOOKS = HOOKS || new Proxy({}, {get:(o, k) => o[k] || (o[k] = [])});"
  grep -m1 '^function mulberry32' "$APP"
  echo "const NIGHT = {uWin:{value:null}, uLit:{value:0}, uNight:{value:0}, uDay:{value:1}};"
  echo "const SG = {on:true, lat0:1.315, lon0:103.845, MX:111290.5, MY:110574};"
  echo "const sgXY = (lat, lon) => [(lon - SG.lon0)*SG.MX, (lat - SG.lat0)*SG.MY], sgLL = (x, y) => [SG.lat0 + y/SG.MY, SG.lon0 + x/SG.MX];"
  echo "const hAt = () => 0, hC = () => 0;"
  sed -n "${a},$((b-1))p" "$APP"
  echo "const LANDMARKS = {}, SG_PLACES = [], SITES = {};"
} > "$K/lmbase.js"
node -e "global.THREE=require('/tmp/claude-0/-home-claude/bad1757d-5741-5c42-90f7-67ab565b955b/scratchpad/vend/package/build/three.min.js');require('vm').runInThisContext(require('fs').readFileSync('$K/lmbase.js','utf8'));console.log('lmbase ok', typeof LBox, typeof lmMerge)"
