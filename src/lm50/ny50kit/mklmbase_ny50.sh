#!/bin/bash
# lm50 NYC: regenerate the node landmark harness lmbase_ny50.js from the built New York app (R/../site/nyc-app.js): the app's own
# helper block (LMCTX ... lmMerge) with node stubs.  usage: bash mklmbase_ny50.sh [nyc-app.js] [out.js]
APP=${1:-/home/claude/earth_online/site/nyc-app.js}; OUT=${2:-$(dirname "$0")/lmbase_ny50.js}
a=$(grep -n '^let LMCTX = null;' "$APP" | head -1 | cut -d: -f1); b=$(grep -n '^const LANDMARKS = {' "$APP" | head -1 | cut -d: -f1)
{ echo "// GENERATED by mklmbase_ny50.sh from $APP lines $a..$((b-1)) — do not edit"
  echo "var HOOKS = HOOKS || new Proxy({}, {get:(o, k) => o[k] || (o[k] = [])});"
  grep -m1 '^function mulberry32' "$APP"
  echo "const NIGHT = {uWin:{value:null}, uLit:{value:0}, uNight:{value:0}, uDay:{value:1}};"
  echo "const SG = {on:true, lat0:40.70, lon0:-73.98, MX:84516, MY:111048};"
  echo "const sgXY = (lat, lon) => [(lon - SG.lon0)*SG.MX, (lat - SG.lat0)*SG.MY], sgLL = (x, y) => [SG.lat0 + y/SG.MY, SG.lon0 + x/SG.MX];"
  echo "const hAt = () => 0, hC = () => 0;"
  sed -n "${a},$((b-1))p" "$APP"
  echo "const LANDMARKS = {}, SG_PLACES = [], SITES = {};"
  # the detail-pass helpers (LShape, archFill, pointedArch, lmWrap, postsRect ...) some modules use
  c=$(grep -n '^function LShape(' "$APP" | head -1 | cut -d: -f1); d=$(grep -n '^// Eiffel Tower' "$APP" | head -1 | cut -d: -f1)
  sed -n "${c},$((d-1))p" "$APP"
  echo "var SGR = (typeof SGR !== 'undefined') ? SGR : {};"
} > "$OUT"
node -e "global.THREE=require('/tmp/claude-0/-home-claude/bad1757d-5741-5c42-90f7-67ab565b955b/scratchpad/vend/package/build/three.min.js');require('vm').runInThisContext(require('fs').readFileSync('$OUT','utf8'));console.log('lmbase_ny50 ok', typeof LBox, typeof lmMerge, typeof LTris)"
